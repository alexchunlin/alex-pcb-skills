#!/usr/bin/env python3
"""Build a project symbol library from the lib_symbols block that `pcb apply schematic` embeds in the generated
.kicad_sch, and write a project sym-lib-table whose empty-nickname entry points at it. The generated schematic
uses bare lib_ids (no "LIB:" prefix); without this table KiCad ERC reports lib_symbol_issues for every symbol.

Usage: make_symlib.py <schematic.kicad_sch> <out.kicad_sym> <sym-lib-table> <uri-for-table>
Re-run after every `pcb apply schematic`.
"""
import sys

sch, out_lib, out_table, uri = sys.argv[1:5]
text = open(sch, encoding="utf-8").read()

def block(text, start_token):
    i = text.index(start_token)
    depth = 0
    in_str = False
    j = i
    while j < len(text):
        c = text[j]
        if in_str:
            if c == "\\":
                j += 2
                continue
            if c == '"':
                in_str = False
        elif c == '"':
            in_str = True
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return text[i : j + 1]
        j += 1
    raise SystemExit("unbalanced")

lib_symbols = block(text, "(lib_symbols")
inner = lib_symbols[len("(lib_symbols") : -1]
header = '(kicad_symbol_lib\n\t(version 20251024)\n\t(generator "make_symlib")\n\t(generator_version "10.0")\n'
with open(out_lib, "w", encoding="utf-8") as f:
    f.write(header + inner.rstrip() + "\n)\n")
with open(out_table, "w", encoding="utf-8") as f:
    f.write('(sym_lib_table\n\t(version 7)\n\t(lib (name "")(type "KiCad")(uri "%s")(options "")(descr "Symbols embedded by pcb apply schematic; regenerated by tools/make_symlib.py"))\n)\n' % uri)
n = inner.count("\n\t(symbol ")
print("wrote", out_lib, "with", n, "symbols;", out_table)
